export type ProductIconKey = keyof typeof productIcons;

/** Resolves an icon key supplied by data, such as a node definition.
 *
 * An unrecognized key falls back rather than failing: a registry from a newer runtime may
 * name an icon this build does not ship, and that must not stop the node from rendering.
 */
export function resolveProductIcon(
  iconKey: string,
  fallback: ProductIconKey,
): ProductIconKey {
  return Object.hasOwn(productIcons, iconKey)
    ? (iconKey as ProductIconKey)
    : fallback;
}
